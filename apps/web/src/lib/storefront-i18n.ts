const EN_PATTERNS: [RegExp, string][] = [
  [/^(.+) أُضيف للسلة$/, '$1 added to cart'],
  [/^تم نسخ الكود: (.+)$/, 'Code copied: $1'],
  [/^(\d+) منتج$/, '$1 products'],
  [/^(\d+) قطعة$/, '$1 pcs'],
  [/^شكراً لطلبك من (.+)$/, 'Thanks for your order from $1'],
];

/** Strings with a dynamic part. */
const CKB_PATTERNS: [RegExp, string][] = [
  [/^(.+) أُضيف للسلة$/, '$1 زیادکرا بۆ سەبەتە'],
  [/^تم نسخ الكود: (.+)$/, 'کۆدەکە کۆپی کرا: $1'],
  [/^(\d+) منتج$/, '$1 بەرهەم'],
  [/^(\d+) قطعة$/, '$1 دانە'],
  [/^شكراً لطلبك من (.+)$/, 'سوپاس بۆ داواکارییەکەت لە $1'],
];

export function translate(text: string, lang: StoreLang): string {
  if (lang === 'ar' || !text) return text;
  const trimmed = text.trim();
  if (!trimmed || !/[؀-ۿ]/.test(trimmed)) return text;
  const hit = (lang === 'en' ? EN : CKB)[trimmed];
  if (hit) return text.replace(trimmed, hit);
  for (const [re, rep] of lang === 'en' ? EN_PATTERNS : CKB_PATTERNS) {
    if (re.test(trimmed)) return text.replace(trimmed, trimmed.replace(re, rep));
  }
  return text;
}

